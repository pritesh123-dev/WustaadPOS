-- "Who is next" token screen
create or replace function public.get_queue()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'shop_name', (select shop_name from public.settings where id = 1),
    'preparing', coalesce((select jsonb_agg(token_no order by token_no) from public.orders
                           where business_date = public.business_date() and status = 'preparing'
                             and order_type <> 'online'), '[]'::jsonb),
    'ready',     coalesce((select jsonb_agg(token_no order by ready_at desc) from public.orders
                           where business_date = public.business_date() and status = 'ready'
                             and order_type <> 'online'), '[]'::jsonb),
    'server_time', now());
$$;

-- Customer checks their own visits & rewards by mobile number (no name is returned)
create or replace function public.check_rewards(p_phone text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_phone text; c public.customers;
begin
  v_phone := public.normalize_phone(p_phone);
  if v_phone is null then raise exception 'Enter a mobile number'; end if;
  select * into c from public.customers where phone = v_phone;
  if not found then
    return jsonb_build_object('found', false,
                              'rewards', public.loyalty_summary(v_phone, 0));
  end if;
  return jsonb_build_object('found', true, 'visits', c.visits, 'last_visit_date', c.last_visit_date,
                            'rewards', public.loyalty_summary(v_phone, c.visits));
end $$;

