-- The "business day" in India time. Orders before day_start_hour (default 4 AM)
-- count towards the previous day, so late-night tokens don't reset at midnight.
create or replace function public.business_date(p_ts timestamptz default now())
returns date language sql stable security definer set search_path = public as $$
  select ((p_ts at time zone 'Asia/Kolkata')
          - make_interval(hours => coalesce((select day_start_hour from public.settings where id = 1), 0)))::date;
$$;

-- Indian financial year label, e.g. 2026-11-09 → '2627'
create or replace function public.fy_label(d date)
returns text language sql immutable as $$
  select case when extract(month from d) >= 4
              then to_char(d, 'YY') || to_char(d + interval '1 year', 'YY')
              else to_char(d - interval '1 year', 'YY') || to_char(d, 'YY') end;
$$;

-- Accepts 9876543210 / +91 98765 43210 / 09876543210 → '9876543210'
create or replace function public.normalize_phone(p text)
returns text language plpgsql immutable as $$
declare d text := regexp_replace(coalesce(p, ''), '\D', '', 'g');
begin
  if d = '' then return null; end if;
  if length(d) = 12 and left(d, 2) = '91' then d := right(d, 10);
  elsif length(d) = 11 and left(d, 1) = '0' then d := right(d, 10);
  end if;
  if d !~ '^[6-9][0-9]{9}$' then
    raise exception 'Invalid mobile number: %', p using errcode = '22023';
  end if;
  return d;
end $$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid() and active);
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid() and active and role = 'admin');
$$;

create or replace function public.require_staff()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_staff() then
    raise exception 'Not allowed: please log in with a staff account' using errcode = '42501';
  end if;
end $$;

create or replace function public.require_admin()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'Not allowed: admin only' using errcode = '42501';
  end if;
end $$;

-- Reward position of a customer at a given visit count.
create or replace function public.reward_status(p_phone text, p_visits int)
returns table (rule_id bigint, name text, visits_required int, reward_item_id bigint,
               reward_item_name text, reward_qty int, repeating boolean,
               earned int, redeemed int, available int, visits_to_next int)
language sql stable security definer set search_path = public as $$
  select r.id, r.name, r.visits_required, r.reward_item_id, m.name, r.reward_qty, r.repeating,
         e.earned,
         x.cnt,
         greatest(e.earned - x.cnt, 0),
         case when r.repeating or p_visits < r.visits_required
              then r.visits_required - (p_visits % r.visits_required) end
  from public.reward_rules r
  join public.menu_items m on m.id = r.reward_item_id
  cross join lateral (
    select case when r.repeating then p_visits / r.visits_required
                else (p_visits >= r.visits_required)::int end as earned) e
  cross join lateral (
    select count(*)::int as cnt from public.reward_redemptions d
    where d.phone = p_phone and d.rule_id = r.id) x
  where r.active
  order by r.visits_required, r.id;
$$;

create or replace function public.loyalty_summary(p_phone text, p_visits int)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(s)), '[]'::jsonb)
  from public.reward_status(p_phone, p_visits) s;
$$;

-- Full order (with items + loyalty info) as JSON, used for screens and receipts.
create or replace function public.order_json(p_id uuid)
returns jsonb language sql stable security definer set search_path = public as $$
  select to_jsonb(o) || jsonb_build_object(
    'items', coalesce((select jsonb_agg(to_jsonb(i) order by i.is_reward, i.id)
                       from public.order_items i where i.order_id = o.id), '[]'::jsonb),
    'loyalty', case when c.phone is null then null else jsonb_build_object(
                 'visits', c.visits,
                 'rewards', public.loyalty_summary(c.phone, c.visits)) end,
    'created_by_name', (select s.name from public.staff s where s.user_id = o.created_by))
  from public.orders o
  left join public.customers c on c.phone = o.customer_phone
  where o.id = p_id;
$$;

