-- Look up a customer by mobile before billing: visits + rewards they can use now.
create or replace function public.lookup_customer(p_phone text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_phone   text;
  c         public.customers;
  v_counts  boolean;
  v_preview int;
begin
  perform public.require_staff();
  v_phone := public.normalize_phone(p_phone);
  if v_phone is null then raise exception 'Enter a mobile number'; end if;
  select * into c from public.customers where phone = v_phone;
  -- Only one visit per customer per business day is counted.
  v_counts := not exists (select 1 from public.orders o
                          where o.customer_phone = v_phone and o.business_date = public.business_date()
                            and o.counted_visit and o.status <> 'cancelled');
  v_preview := coalesce(c.visits, 0) + case when v_counts then 1 else 0 end;
  return jsonb_build_object(
    'found', c.phone is not null,
    'phone', v_phone,
    'name', c.name,
    'visits', coalesce(c.visits, 0),
    'total_spent', coalesce(c.total_spent, 0),
    'last_visit_date', c.last_visit_date,
    'visit_counts_today', v_counts,
    'visit_no', v_preview,
    'rewards', public.loyalty_summary(v_phone, v_preview));
end $$;

-- Create an order atomically: token, invoice number, GST, visit count, rewards.
-- p = { client_ref, order_type, table_no, online_source, customer_phone, customer_name,
--       payment_mode, discount, notes, items:[{item_id, qty}], redeem_rule_ids:[...],
--       offline_token, created_at }
create or replace function public.place_order(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s               public.settings;
  v_id            uuid;
  v_client_ref    uuid := nullif(p->>'client_ref', '')::uuid;
  v_type          text := coalesce(nullif(p->>'order_type', ''), 'takeaway');
  v_source        text := lower(nullif(trim(p->>'online_source'), ''));
  v_phone         text := public.normalize_phone(p->>'customer_phone');
  v_name          text := nullif(trim(p->>'customer_name'), '');
  v_pay           text := coalesce(nullif(p->>'payment_mode', ''), 'cash');
  v_discount      numeric := coalesce(nullif(p->>'discount', '')::numeric, 0);
  v_offline_token int := nullif(p->>'offline_token', '')::int;
  v_ts            timestamptz := now();
  v_bdate         date;
  v_token         int;
  v_inv_no        int;
  v_fy            text;
  v_counts        boolean := false;
  v_visits        int := 0;
  v_rate          numeric;
  v_tax_note      text;
  v_sub           numeric := 0;
  v_taxable       numeric;
  v_tax           numeric;
  v_cgst          numeric;
  v_sgst          numeric;
  v_gross         numeric;
  v_total         numeric;
  v_lines         int := 0;
  v_avail         int;
  v_item          public.menu_items;
  r               record;
begin
  perform public.require_staff();

  -- Already synced? (offline retry) → return the existing order
  if v_client_ref is not null then
    select id into v_id from public.orders where client_ref = v_client_ref;
    if found then return public.order_json(v_id); end if;
  end if;

  if v_type not in ('dine_in', 'takeaway', 'online') then raise exception 'Invalid order type: %', v_type; end if;
  if v_pay not in ('cash', 'upi', 'card', 'online', 'unpaid') then raise exception 'Invalid payment mode: %', v_pay; end if;
  if v_discount < 0 then raise exception 'Discount cannot be negative'; end if;
  if jsonb_typeof(p->'items') is distinct from 'array' then raise exception 'items must be a list'; end if;

  -- Bills made offline keep their original time
  if nullif(p->>'created_at', '') is not null then
    v_ts := (p->>'created_at')::timestamptz;
    if v_ts > now() + interval '10 minutes' or v_ts < now() - interval '7 days' then v_ts := now(); end if;
  end if;

  select * into s from public.settings where id = 1;
  v_bdate := public.business_date(v_ts);

  -- Customer + visit counting (max one visit per business day)
  if v_phone is not null then
    insert into public.customers (phone, name) values (v_phone, v_name)
      on conflict (phone) do update set name = coalesce(excluded.name, public.customers.name);
    select visits into v_visits from public.customers where phone = v_phone for update;
    v_counts := not exists (select 1 from public.orders o
                            where o.customer_phone = v_phone and o.business_date = v_bdate
                              and o.counted_visit and o.status <> 'cancelled');
    if v_counts then
      v_visits := v_visits + 1;
      update public.customers
         set visits = v_visits,
             last_visit_date = greatest(coalesce(last_visit_date, v_bdate), v_bdate)
       where phone = v_phone;
    end if;
  end if;

  -- Token number (resets every business day). Offline bills bring their own token (900+).
  if v_offline_token is not null
     and not exists (select 1 from public.orders where business_date = v_bdate and token_no = v_offline_token) then
    v_token := v_offline_token;
  else
    insert into public.token_counters as t (business_date, last_token) values (v_bdate, 1)
      on conflict (business_date) do update set last_token = t.last_token + 1
      returning last_token into v_token;
    while exists (select 1 from public.orders where business_date = v_bdate and token_no = v_token) loop
      update public.token_counters set last_token = last_token + 1
       where business_date = v_bdate returning last_token into v_token;
    end loop;
  end if;

  -- Invoice number: consecutive within the financial year (GST rule)
  v_fy := public.fy_label(v_bdate);
  insert into public.invoice_counters as ic (fy, last_no) values (v_fy, 1)
    on conflict (fy) do update set last_no = ic.last_no + 1
    returning last_no into v_inv_no;

  -- Swiggy/Zomato pay GST on restaurant orders themselves (Sec 9(5)), so no GST on our bill.
  if v_type = 'online' and v_source in ('swiggy', 'zomato') then
    v_rate := 0;
    v_tax_note := 'GST on this order is paid by the delivery platform (Sec 9(5) CGST Act)';
  else
    v_rate := s.gst_rate;
  end if;

  insert into public.orders (client_ref, invoice_no, token_no, business_date, order_type, table_no,
                             online_source, customer_phone, customer_name, payment_mode, gst_rate,
                             tax_note, counted_visit, visit_no, notes, created_by, created_at)
  values (v_client_ref,
          s.invoice_prefix || '/' || v_fy || '/' || lpad(v_inv_no::text, 5, '0'),
          v_token, v_bdate, v_type,
          case when v_type = 'dine_in' then nullif(trim(p->>'table_no'), '') end,
          case when v_type = 'online' then coalesce(v_source, 'other') end,
          v_phone, v_name, v_pay, v_rate, v_tax_note, v_counts,
          case when v_phone is not null then v_visits end,
          nullif(trim(p->>'notes'), ''), auth.uid(), v_ts)
  returning id into v_id;

  -- Paid items: prices always come from the menu table, never from the tablet
  for r in select (e->>'item_id')::bigint as item_id, (e->>'qty')::int as qty
           from jsonb_array_elements(p->'items') e loop
    if r.qty is null or r.qty < 1 or r.qty > 500 then raise exception 'Invalid quantity'; end if;
    select * into v_item from public.menu_items where id = r.item_id;
    if not found then raise exception 'Menu item % no longer exists', r.item_id; end if;
    insert into public.order_items (order_id, item_id, name, price, qty, line_total)
    values (v_id, v_item.id, v_item.name, v_item.price, r.qty, v_item.price * r.qty);
    v_sub := v_sub + v_item.price * r.qty;
    v_lines := v_lines + 1;
  end loop;

  -- Free reward items
  if jsonb_typeof(p->'redeem_rule_ids') = 'array' and jsonb_array_length(p->'redeem_rule_ids') > 0 then
    if v_phone is null then raise exception 'Customer mobile number is required to redeem a reward'; end if;
    for r in select (e #>> '{}')::bigint as rule_id, count(*)::int as n
             from jsonb_array_elements(p->'redeem_rule_ids') e group by 1 loop
      select st.available into v_avail from public.reward_status(v_phone, v_visits) st where st.rule_id = r.rule_id;
      if coalesce(v_avail, 0) < r.n then raise exception 'This reward is not available for the customer yet'; end if;
      for i in 1 .. r.n loop
        insert into public.order_items (order_id, item_id, name, price, qty, line_total, is_reward, reward_rule_id)
        select v_id, m.id, m.name, 0, rr.reward_qty, 0, true, rr.id
          from public.reward_rules rr join public.menu_items m on m.id = rr.reward_item_id
         where rr.id = r.rule_id;
        insert into public.reward_redemptions (phone, rule_id, order_id) values (v_phone, r.rule_id, v_id);
        v_lines := v_lines + 1;
      end loop;
    end loop;
  end if;

  if v_lines = 0 then raise exception 'The order has no items'; end if;

  -- GST
  v_discount := least(v_discount, v_sub);
  if s.prices_include_gst then
    v_gross   := v_sub - v_discount;
    v_taxable := round(v_gross / (1 + v_rate / 100), 2);
    v_tax     := v_gross - v_taxable;
    v_cgst    := round(v_tax / 2, 2);
    v_sgst    := v_tax - v_cgst;
  else
    v_taxable := v_sub - v_discount;
    v_cgst    := round(v_taxable * v_rate / 200, 2);
    v_sgst    := v_cgst;
    v_gross   := v_taxable + v_cgst + v_sgst;
  end if;
  v_total := round(v_gross);

  update public.orders
     set subtotal = v_sub, discount = v_discount, taxable_value = v_taxable,
         cgst = v_cgst, sgst = v_sgst, round_off = v_total - v_gross, total = v_total, updated_at = now()
   where id = v_id;

  if v_phone is not null then
    update public.customers set total_spent = total_spent + v_total where phone = v_phone;
  end if;

  return public.order_json(v_id);
end $$;

create or replace function public.get_order(p_id uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.require_staff();
  return public.order_json(p_id);
end $$;

-- preparing → ready → completed, or cancelled (with reason).
-- Cashiers can cancel only within 15 minutes; admins any time.
create or replace function public.set_order_status(p_id uuid, p_status text, p_reason text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  perform public.require_staff();
  select * into o from public.orders where id = p_id for update;
  if not found then raise exception 'Order not found'; end if;
  if o.status = 'cancelled' then raise exception 'This order is already cancelled'; end if;
  if p_status not in ('preparing', 'ready', 'completed', 'cancelled') then
    raise exception 'Invalid status: %', p_status;
  end if;

  if p_status = 'cancelled' then
    if nullif(trim(p_reason), '') is null then raise exception 'Please give a reason for cancelling'; end if;
    if not public.is_admin() and o.created_at < now() - interval '15 minutes' then
      raise exception 'Only an admin can cancel an order older than 15 minutes';
    end if;
    if o.customer_phone is not null then
      update public.customers
         set visits = greatest(visits - case when o.counted_visit then 1 else 0 end, 0),
             total_spent = greatest(total_spent - o.total, 0)
       where phone = o.customer_phone;
    end if;
    delete from public.reward_redemptions where order_id = o.id;   -- give the reward back
    update public.orders
       set status = 'cancelled', cancel_reason = trim(p_reason), counted_visit = false, updated_at = now()
     where id = o.id;
  else
    update public.orders
       set status = p_status,
           ready_at = case when p_status = 'ready' then coalesce(ready_at, now())
                           when p_status = 'preparing' then null else ready_at end,
           completed_at = case when p_status = 'completed' then now() end,
           updated_at = now()
     where id = o.id;
  end if;
  return public.order_json(p_id);
end $$;

-- Orders list with filters. Cashiers only see today + yesterday.
-- p = { from, to, status:[...], order_type, search, limit, offset }
create or replace function public.list_orders(p jsonb default '{}'::jsonb)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_from   date := coalesce(nullif(p->>'from', '')::date, public.business_date());
  v_to     date := coalesce(nullif(p->>'to', '')::date, coalesce(nullif(p->>'from', '')::date, public.business_date()));
  v_status text[] := case when jsonb_typeof(p->'status') = 'array'
                          then array(select jsonb_array_elements_text(p->'status')) end;
  v_type   text := nullif(p->>'order_type', '');
  v_q      text := nullif(trim(p->>'search'), '');
  v_limit  int  := least(coalesce(nullif(p->>'limit', '')::int, 200), 5000);
  v_offset int  := greatest(coalesce(nullif(p->>'offset', '')::int, 0), 0);
  v_total  int;
  v_rows   jsonb;
begin
  perform public.require_staff();
  if not public.is_admin() then v_from := greatest(v_from, public.business_date() - 1); end if;

  with f as (
    select o.id, o.created_at from public.orders o
     where o.business_date between v_from and v_to
       and (v_status is null or o.status = any (v_status))
       and (v_type is null or o.order_type = v_type)
       and (v_q is null
            or o.invoice_no ilike '%' || v_q || '%'
            or o.customer_phone like '%' || v_q || '%'
            or o.customer_name ilike '%' || v_q || '%'
            or o.token_no::text = v_q)
  )
  select (select count(*) from f),
         coalesce((select jsonb_agg(public.order_json(x.id) order by x.created_at desc)
                   from (select id, created_at from f order by created_at desc
                         limit v_limit offset v_offset) x), '[]'::jsonb)
    into v_total, v_rows;

  return jsonb_build_object('total', v_total, 'rows', v_rows);
end $$;

