create or replace function public.sales_report(p_from date, p_to date)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  perform public.require_admin();
  with o  as (select * from public.orders where business_date between p_from and p_to),
       ok as (select * from o where status <> 'cancelled'),
       it as (select i.* from public.order_items i join ok on ok.id = i.order_id)
  select jsonb_build_object(
    'from', p_from, 'to', p_to,
    'summary', (select jsonb_build_object(
                  'orders', count(*), 'total', coalesce(sum(total), 0),
                  'taxable', coalesce(sum(taxable_value), 0),
                  'cgst', coalesce(sum(cgst), 0), 'sgst', coalesce(sum(sgst), 0),
                  'discount', coalesce(sum(discount), 0),
                  'avg_ticket', coalesce(round(avg(total), 2), 0),
                  'unique_customers', count(distinct customer_phone)) from ok),
    'cancelled', (select jsonb_build_object('orders', count(*), 'total', coalesce(sum(total), 0))
                  from o where status = 'cancelled'),
    'by_day', coalesce((select jsonb_agg(d order by d.date) from
                (select business_date as date, count(*) as orders, sum(total) as total
                   from ok group by business_date) d), '[]'::jsonb),
    'by_type', coalesce((select jsonb_agg(d order by d.total desc) from
                (select order_type, count(*) as orders, sum(total) as total
                   from ok group by order_type) d), '[]'::jsonb),
    'by_payment', coalesce((select jsonb_agg(d order by d.total desc) from
                (select payment_mode, count(*) as orders, sum(total) as total
                   from ok group by payment_mode) d), '[]'::jsonb),
    'by_hour', coalesce((select jsonb_agg(d order by d.hour) from
                (select extract(hour from created_at at time zone 'Asia/Kolkata')::int as hour,
                        count(*) as orders, sum(total) as total
                   from ok group by 1) d), '[]'::jsonb),
    'top_items', coalesce((select jsonb_agg(t) from
                (select name,
                        coalesce(sum(qty) filter (where not is_reward), 0) as qty,
                        coalesce(sum(qty) filter (where is_reward), 0) as free_qty,
                        sum(line_total) as amount
                   from it group by name order by sum(line_total) desc, name limit 20) t), '[]'::jsonb),
    'rewards_redeemed', (select count(*) from it where is_reward),
    'new_customers', (select count(*) from public.customers
                      where public.business_date(created_at) between p_from and p_to)
  ) into v;
  return v;
end $$;

create or replace function public.list_staff()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.require_admin();
  return coalesce((select jsonb_agg(jsonb_build_object(
            'user_id', s.user_id, 'name', s.name, 'role', s.role, 'active', s.active,
            'email', u.email, 'created_at', s.created_at) order by s.role, s.name)
          from public.staff s join auth.users u on u.id = s.user_id), '[]'::jsonb);
end $$;

-- The login itself is created in Supabase → Authentication → Users → Add user.
create or replace function public.add_staff(p_email text, p_name text, p_role text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid;
begin
  perform public.require_admin();
  if p_role not in ('admin', 'cashier') then raise exception 'Role must be admin or cashier'; end if;
  select id into v_uid from auth.users where lower(email) = lower(trim(p_email));
  if not found then
    raise exception 'No login found for %. First create it in Supabase → Authentication → Users → Add user.', p_email;
  end if;
  insert into public.staff (user_id, name, role, active) values (v_uid, trim(p_name), p_role, true)
    on conflict (user_id) do update set name = excluded.name, role = excluded.role, active = true;
  return public.list_staff();
end $$;

create or replace function public.update_staff(p_user_id uuid, p_name text, p_role text, p_active boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public.require_admin();
  if p_role not in ('admin', 'cashier') then raise exception 'Role must be admin or cashier'; end if;
  update public.staff set name = trim(p_name), role = p_role, active = p_active where user_id = p_user_id;
  if not exists (select 1 from public.staff where role = 'admin' and active) then
    raise exception 'At least one active admin is required';
  end if;
  return public.list_staff();
end $$;

create or replace function public.update_customer(p_phone text, p_name text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.require_staff();
  update public.customers set name = nullif(trim(p_name), '') where phone = public.normalize_phone(p_phone);
end $$;

-- Remove a customer's personal data on request (their past bills stay, without the number).
create or replace function public.delete_customer(p_phone text)
returns void language plpgsql security definer set search_path = public as $$
declare v_phone text := public.normalize_phone(p_phone);
begin
  perform public.require_admin();
  update public.orders set customer_name = null where customer_phone = v_phone;
  delete from public.customers where phone = v_phone;
end $$;

