-- Shop-wide settings (exactly one row, id = 1)
create table public.settings (
  id                 int primary key default 1 check (id = 1),
  shop_name          text not null default 'Wustaad',
  tagline            text not null default 'Hyderabadi Biryani & Chinese',
  address            text not null default '',
  phone              text not null default '',
  gstin              text not null default '',
  fssai              text not null default '',
  gst_rate           numeric(5,2) not null default 5.00 check (gst_rate >= 0 and gst_rate <= 28),
  prices_include_gst boolean not null default false,
  invoice_prefix     text not null default 'WS' check (invoice_prefix ~ '^[A-Z0-9]{1,4}$'),
  day_start_hour     int  not null default 4 check (day_start_hour between 0 and 12),
  bill_footer        text not null default 'Thank you! Visit again.',
  updated_at         timestamptz not null default now()
);
insert into public.settings (id) values (1);

-- Staff profiles. Each row links a Supabase Auth login to a role.
create table public.staff (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  name       text not null,
  role       text not null default 'cashier' check (role in ('admin', 'cashier')),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.categories (
  id     bigint generated by default as identity primary key,
  name   text not null unique,
  sort   int not null default 0,
  active boolean not null default true
);

create table public.menu_items (
  id          bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name        text not null,
  price       numeric(10,2) not null check (price >= 0),
  is_veg      boolean not null default false,
  available   boolean not null default true,
  sort        int not null default 0,
  created_at  timestamptz not null default now()
);

-- Customers are identified by their 10-digit mobile number.
create table public.customers (
  phone           text primary key check (phone ~ '^[6-9][0-9]{9}$'),
  name            text,
  visits          int not null default 0,
  total_spent     numeric(12,2) not null default 0,
  last_visit_date date,
  created_at      timestamptz not null default now()
);

-- "Every N visits → free item" rules, managed by the admin.
create table public.reward_rules (
  id              bigint generated by default as identity primary key,
  name            text not null,
  visits_required int not null check (visits_required >= 1),
  reward_item_id  bigint not null references public.menu_items(id),
  reward_qty      int not null default 1 check (reward_qty >= 1),
  repeating       boolean not null default true,   -- true: every N visits, false: once only
  active          boolean not null default true,
  created_at      timestamptz not null default now()
);

create table public.orders (
  id             uuid primary key default gen_random_uuid(),
  client_ref     uuid unique,                -- set by the tablet; makes offline re-sync safe
  invoice_no     text not null unique,       -- e.g. WS/2627/00042 (resets every financial year)
  token_no       int  not null,              -- order number shown to customers (resets daily)
  business_date  date not null,
  order_type     text not null check (order_type in ('dine_in', 'takeaway', 'online')),
  table_no       text,
  online_source  text,                       -- swiggy / zomato / website / phone / other
  customer_phone text references public.customers(phone) on delete set null,
  customer_name  text,
  status         text not null default 'preparing'
                 check (status in ('preparing', 'ready', 'completed', 'cancelled')),
  payment_mode   text not null default 'cash'
                 check (payment_mode in ('cash', 'upi', 'card', 'online', 'unpaid')),
  subtotal       numeric(12,2) not null default 0,
  discount       numeric(12,2) not null default 0,
  taxable_value  numeric(12,2) not null default 0,
  gst_rate       numeric(5,2)  not null default 0,
  cgst           numeric(12,2) not null default 0,
  sgst           numeric(12,2) not null default 0,
  round_off      numeric(6,2)  not null default 0,
  total          numeric(12,2) not null default 0,
  tax_note       text,
  counted_visit  boolean not null default false,
  visit_no       int,
  notes          text,
  cancel_reason  text,
  created_by     uuid references auth.users(id) on delete set null,
  created_at     timestamptz not null default now(),
  ready_at       timestamptz,
  completed_at   timestamptz,
  updated_at     timestamptz not null default now(),
  unique (business_date, token_no)
);
create index orders_business_date_idx on public.orders (business_date, status);
create index orders_customer_idx on public.orders (customer_phone, business_date);

create table public.order_items (
  id             bigint generated by default as identity primary key,
  order_id       uuid not null references public.orders(id) on delete cascade,
  item_id        bigint references public.menu_items(id) on delete set null,
  name           text not null,
  price          numeric(10,2) not null,
  qty            int not null check (qty > 0),
  line_total     numeric(12,2) not null,
  is_reward      boolean not null default false,
  reward_rule_id bigint references public.reward_rules(id) on delete set null
);
create index order_items_order_idx on public.order_items (order_id);

create table public.reward_redemptions (
  id         bigint generated by default as identity primary key,
  phone      text not null references public.customers(phone) on delete cascade,
  rule_id    bigint not null references public.reward_rules(id),
  order_id   uuid not null references public.orders(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index reward_redemptions_phone_idx on public.reward_redemptions (phone, rule_id);

-- Counters (only touched inside functions)
create table public.token_counters   (business_date date primary key, last_token int not null default 0);
create table public.invoice_counters (fy text primary key, last_no int not null default 0);

